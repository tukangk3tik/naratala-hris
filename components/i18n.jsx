// Global current-language state + a simple t() helper
window.__lang = 'id'; // default ID
const t = (key, vars) => {
  const dict = TRANSLATIONS[window.__lang] || TRANSLATIONS.en;
  let s = dict[key];
  if (s == null) s = TRANSLATIONS.en[key] ?? key;
  if (typeof s === 'string' && vars) {
    Object.entries(vars).forEach(([k, v]) => { s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), v); });
  }
  return s;
};

